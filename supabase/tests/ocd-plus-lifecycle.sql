-- Run inside BEGIN/ROLLBACK. No fixtures or changes may be committed.
do $$
declare u uuid := gen_random_uuid(); s uuid; a uuid; payload jsonb;
  before_end timestamptz; n integer; caught boolean; version bigint;
begin
  insert into public.users(id,phone,password,role,name)
    values(u,'test-'||u,'disabled-test-password','customer','OCD integration transaction test');
  payload := public.ocd_begin_checkout(u,'gid://shopify/Customer/1');
  a := (payload->>'attempt_id')::uuid; s := (payload->>'subscription_id')::uuid;
  assert payload->>'created'='true', 'First checkout must create an attempt';
  payload := public.ocd_begin_checkout(u,'gid://shopify/Customer/1');
  assert payload->>'created'='false' and (payload->>'attempt_id')::uuid=a, 'Double tap must reuse attempt';
  caught := false;
  begin perform public.ocd_apply_payment(a,'test-'||u,'999',true,48,'ILS');
  exception when others then caught := true; end;
  assert caught, 'Wrong amount accepted';
  assert not exists(select 1 from public.ocd_plus_payment_events where subscription_id=s), 'Rejected payment must not be recorded';
  perform public.ocd_apply_payment(a,'test-'||u,'999',true,49,'ILS');
  assert (select ocd_plus_subscriber from public.users where id=u), 'Payment must activate app access';
  select current_period_end,sync_version into before_end,version from public.ocd_plus_subscriptions where id=s;
  assert before_end > now()+interval '27 days', 'Expected a paid month';
  perform public.ocd_apply_payment(a,'test-'||u,'999',true,49,'ILS');
  assert (select current_period_end=before_end and sync_version=version from public.ocd_plus_subscriptions where id=s), 'Duplicate extended access';
  assert (select count(*)=1 from public.ocd_plus_payment_events where subscription_id=s), 'Duplicate ledger event';
  caught := false;
  begin perform public.ocd_apply_payment(a,'test-'||u,'999',false,49,'ILS');
  exception when others then caught := true; end;
  assert caught, 'Conflicting payment status accepted';
  caught := false;
  begin perform public.ocd_apply_payment(a,'renewal-'||u,'999',true,49,'ILS');
  exception when others then caught := true; end;
  assert caught, 'Renewal without verified date accepted';
  perform public.ocd_apply_payment(a,'older-'||u,'999',true,49,'ILS',now()-interval '2 months');
  assert (select current_period_end=before_end from public.ocd_plus_subscriptions where id=s), 'Older payment shortened access';
  perform public.ocd_apply_payment(a,'old-failure-'||u,'999',false,49,'ILS',now()-interval '1 day');
  assert (select status='active' from public.ocd_plus_subscriptions where id=s), 'Old failure overrode newer payment';
  caught := false;
  begin perform public.ocd_apply_payment(a,'different-agreement-'||u,'997',true,49,'ILS',now());
  exception when others then caught := true; end;
  assert caught, 'Second recurring agreement silently replaced original';
  select count(*) into n from public.ocd_claim_sync(s);
  assert n=1, 'Pending sync not claimed';
  select count(*) into n from public.ocd_claim_sync(s);
  assert n=0, 'Second worker acquired active lease';
  update public.ocd_plus_subscriptions set sync_until=now()-interval '1 minute' where id=s;
  select count(*) into n from public.ocd_claim_sync(s);
  assert n=1, 'Expired worker lease not recoverable';
  perform public.ocd_request_cancel(u);
  assert (select cancel_requested_at is not null and not cancel_at_period_end from public.ocd_plus_subscriptions where id=s), 'Request must not claim provider cancellation';
  update public.ocd_plus_subscriptions set current_period_end=now()-interval '1 second',cancel_at_period_end=true,provider_cancelled_at=now() where id=s;
  perform public.ocd_expire_memberships();
  assert (select status='cancelled' from public.ocd_plus_subscriptions where id=s), 'Expired cancellation not finalized';
  assert not (select ocd_plus_subscriber from public.users where id=u), 'Expired member still entitled';
  payload := public.ocd_begin_checkout(u,'gid://shopify/Customer/1');
  assert payload->>'created'='true', 'Confirmed cancelled customer cannot rejoin';
  perform public.ocd_apply_payment((payload->>'attempt_id')::uuid,'rejoin-'||u,'998',true,49,'ILS');
  assert (select next_billing_at is not null and cancel_requested_at is null and not cancel_at_period_end from public.ocd_plus_subscriptions where id=s), 'Rejoin kept cancellation state';
  assert not has_function_privilege('anon','public.ocd_apply_payment(uuid,text,text,boolean,numeric,text,timestamptz)','EXECUTE'), 'Anonymous payment RPC access';
  assert not has_function_privilege('authenticated','public.ocd_request_cancel(uuid)','EXECUTE'), 'Client can cancel another customer via RPC';
  assert not has_table_privilege('anon','public.ocd_plus_payment_attempts','SELECT'), 'Client can read signed payment links';
end $$;
select 'OCD lifecycle assertions passed; transaction will roll back' as test_result;
